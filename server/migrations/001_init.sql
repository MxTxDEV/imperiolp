-- Império ERP — esquema inicial.
-- Convenções: ids TEXT gerados no servidor; dinheiro em CENTAVOS inteiros (colunas terminadas em C);
-- datas 'AAAA-MM-DD'; carimbos de tempo em ISO UTC; totais NUNCA são colunas (sempre derivados).
-- "ativo = 0" significa arquivado (nunca apagamos o que tem histórico).

CREATE TABLE roles (
  id TEXT PRIMARY KEY, nome TEXT NOT NULL, descricao TEXT NOT NULL DEFAULT '',
  permissoes TEXT NOT NULL DEFAULT '[]', sistema INTEGER NOT NULL DEFAULT 0, ativo INTEGER NOT NULL DEFAULT 1,
  versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE TABLE users (
  id TEXT PRIMARY KEY, nome TEXT NOT NULL, email TEXT NOT NULL, senhaHash TEXT NOT NULL,
  senhaTemp INTEGER NOT NULL DEFAULT 0, roleId TEXT NOT NULL REFERENCES roles(id) DEFERRABLE INITIALLY IMMEDIATE, ultimoLogin TEXT,
  ativo INTEGER NOT NULL DEFAULT 1, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE UNIQUE INDEX ux_roles_nome ON roles(lower(nome));
CREATE UNIQUE INDEX ux_users_email ON users(lower(email));
CREATE TABLE sessions (
  tokenHash TEXT PRIMARY KEY, userId TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  criadoEm TEXT NOT NULL, expiraEm TEXT NOT NULL, ultimoUso TEXT NOT NULL, ip TEXT, ua TEXT
);
CREATE INDEX ix_sessions_user ON sessions(userId);
CREATE TABLE loginAttempts (chave TEXT PRIMARY KEY, falhas INTEGER NOT NULL DEFAULT 0, bloqueadoAte TEXT, atualizadoEm TEXT NOT NULL);
CREATE TABLE auditLog (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ts TEXT NOT NULL, userId TEXT, userNome TEXT, acao TEXT NOT NULL,
  entidade TEXT NOT NULL, entidadeId TEXT, resumo TEXT NOT NULL DEFAULT '', antes TEXT, depois TEXT
);
CREATE INDEX ix_audit_ts ON auditLog(ts);
CREATE INDEX ix_audit_ent ON auditLog(entidade, entidadeId);
CREATE TABLE meta (chave TEXT PRIMARY KEY, valor TEXT NOT NULL);

-- ---------- cadastros ----------
CREATE TABLE empreendimentos (
  id TEXT PRIMARY KEY, nome TEXT NOT NULL, tipo TEXT NOT NULL DEFAULT 'Condomínio de apartamentos',
  status TEXT NOT NULL DEFAULT 'Lançamento' CHECK (status IN ('Lançamento','Em obras','Entregue')),
  cidade TEXT NOT NULL DEFAULT '', bairro TEXT NOT NULL DEFAULT '', unidadesPrevistas INTEGER NOT NULL DEFAULT 0 CHECK (unidadesPrevistas >= 0),
  vgvC BIGINT NOT NULL DEFAULT 0 CHECK (vgvC >= 0), entrega TEXT,
  ativo INTEGER NOT NULL DEFAULT 1, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE UNIQUE INDEX ux_emp_nome ON empreendimentos(lower(nome)) WHERE ativo = 1;

CREATE TABLE clientes (
  id TEXT PRIMARY KEY, tipo TEXT NOT NULL DEFAULT 'PF' CHECK (tipo IN ('PF','PJ')), nome TEXT NOT NULL, documento TEXT,
  email TEXT NOT NULL DEFAULT '', telefone TEXT NOT NULL DEFAULT '', cep TEXT NOT NULL DEFAULT '', endereco TEXT NOT NULL DEFAULT '',
  cidade TEXT NOT NULL DEFAULT '', uf TEXT NOT NULL DEFAULT '', obs TEXT NOT NULL DEFAULT '',
  ativo INTEGER NOT NULL DEFAULT 1, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE UNIQUE INDEX ux_clientes_doc ON clientes(documento) WHERE documento IS NOT NULL AND documento <> '';

CREATE TABLE unidades (
  id TEXT PRIMARY KEY, empId TEXT NOT NULL REFERENCES empreendimentos(id) DEFERRABLE INITIALLY IMMEDIATE, codigo TEXT NOT NULL, tipo TEXT NOT NULL DEFAULT '',
  area DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (area >= 0), valorTabelaC BIGINT NOT NULL DEFAULT 0 CHECK (valorTabelaC >= 0),
  status TEXT NOT NULL DEFAULT 'Disponível' CHECK (status IN ('Disponível','Reservada','Vendida','Bloqueada')),
  clienteId TEXT REFERENCES clientes(id) DEFERRABLE INITIALLY IMMEDIATE, reservaAte TEXT,
  ativo INTEGER NOT NULL DEFAULT 1, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE UNIQUE INDEX ux_unidades_cod ON unidades(empId, lower(codigo)) WHERE ativo = 1;
CREATE INDEX ix_unidades_emp ON unidades(empId, status);

CREATE TABLE fornecedores (
  id TEXT PRIMARY KEY, nome TEXT NOT NULL, documento TEXT, categoria TEXT NOT NULL DEFAULT '', prazo INTEGER NOT NULL DEFAULT 0 CHECK (prazo >= 0),
  telefone TEXT NOT NULL DEFAULT '', email TEXT NOT NULL DEFAULT '', contato TEXT NOT NULL DEFAULT '',
  ativo INTEGER NOT NULL DEFAULT 1, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE UNIQUE INDEX ux_forn_nome ON fornecedores(lower(nome)) WHERE ativo = 1;
CREATE UNIQUE INDEX ux_forn_doc ON fornecedores(documento) WHERE documento IS NOT NULL AND documento <> '';

CREATE TABLE materiais (
  id TEXT PRIMARY KEY, nome TEXT NOT NULL, categoria TEXT NOT NULL DEFAULT 'Outros', unidade TEXT NOT NULL DEFAULT 'un',
  estoque DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (estoque >= 0),      -- mantido SÓ pelas movimentações
  minimo DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (minimo >= 0),
  custoMedioC BIGINT NOT NULL DEFAULT 0 CHECK (custoMedioC >= 0),
  fornId TEXT REFERENCES fornecedores(id) DEFERRABLE INITIALLY IMMEDIATE, local TEXT NOT NULL DEFAULT '',
  ativo INTEGER NOT NULL DEFAULT 1, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE UNIQUE INDEX ux_mat_nome ON materiais(lower(nome)) WHERE ativo = 1;


-- ---------- obras ----------
CREATE TABLE obras (
  id TEXT PRIMARY KEY, nome TEXT NOT NULL, empId TEXT REFERENCES empreendimentos(id) DEFERRABLE INITIALLY IMMEDIATE,
  tipoObra TEXT NOT NULL DEFAULT 'Padrão' CHECK (tipoObra IN ('Padrão','Placas')),
  planta TEXT NOT NULL DEFAULT 'Retangular' CHECK (planta IN ('Retangular','Quadrada','Em L','Em U')),
  pausada INTEGER NOT NULL DEFAULT 0, orcamentoC BIGINT NOT NULL DEFAULT 0 CHECK (orcamentoC >= 0),
  inicio TEXT NOT NULL, previsao TEXT NOT NULL, resp TEXT NOT NULL DEFAULT '', endereco TEXT NOT NULL DEFAULT '',
  ativo INTEGER NOT NULL DEFAULT 1, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT,
  CHECK (previsao >= inicio)
);
CREATE UNIQUE INDEX ux_obras_nome ON obras(lower(nome)) WHERE ativo = 1;
CREATE INDEX ix_obras_emp ON obras(empId);

CREATE TABLE passos (
  id TEXT PRIMARY KEY, obraId TEXT NOT NULL REFERENCES obras(id) DEFERRABLE INITIALLY IMMEDIATE, ordem INTEGER NOT NULL, nome TEXT NOT NULL,
  fase TEXT NOT NULL DEFAULT '', ini TEXT NOT NULL, fim TEXT NOT NULL, peso INTEGER NOT NULL DEFAULT 1 CHECK (peso >= 1),
  status TEXT NOT NULL DEFAULT 'Pendente' CHECK (status IN ('Pendente','Em andamento','Concluído')),
  pct INTEGER NOT NULL DEFAULT 0 CHECK (pct >= 0 AND pct <= 100), dataConc TEXT, extraC BIGINT NOT NULL DEFAULT 0 CHECK (extraC >= 0), obs TEXT NOT NULL DEFAULT '',
  versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT,
  CHECK (fim >= ini)
);
CREATE INDEX ix_passos_obra ON passos(obraId, ordem);
CREATE TABLE passoMateriais (
  passoId TEXT NOT NULL REFERENCES passos(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE, matId TEXT NOT NULL REFERENCES materiais(id) DEFERRABLE INITIALLY IMMEDIATE, qtd DOUBLE PRECISION NOT NULL CHECK (qtd > 0),
  PRIMARY KEY (passoId, matId)
);

CREATE TABLE funcionarios (
  id TEXT PRIMARY KEY, nome TEXT NOT NULL, cpf TEXT, cargo TEXT NOT NULL DEFAULT '',
  vinculo TEXT NOT NULL DEFAULT 'CLT' CHECK (vinculo IN ('CLT','Terceiro','Autônomo','Estagiário')),
  status TEXT NOT NULL DEFAULT 'Ativo' CHECK (status IN ('Ativo','Férias','Afastado','Desligado')),
  obraId TEXT REFERENCES obras(id) DEFERRABLE INITIALLY IMMEDIATE, salarioC BIGINT NOT NULL DEFAULT 0 CHECK (salarioC >= 0), encargosPct DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (encargosPct >= 0 AND encargosPct <= 300),
  admissao TEXT, desligamento TEXT, telefone TEXT NOT NULL DEFAULT '', email TEXT NOT NULL DEFAULT '', ctps TEXT NOT NULL DEFAULT '',
  ativo INTEGER NOT NULL DEFAULT 1, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE UNIQUE INDEX ux_func_cpf ON funcionarios(cpf) WHERE cpf IS NOT NULL AND cpf <> '';

-- ---------- estoque ----------
CREATE TABLE pedidos (
  id TEXT PRIMARY KEY, numero INTEGER NOT NULL UNIQUE, fornId TEXT NOT NULL REFERENCES fornecedores(id) DEFERRABLE INITIALLY IMMEDIATE, obraId TEXT REFERENCES obras(id) DEFERRABLE INITIALLY IMMEDIATE,
  data TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'Rascunho' CHECK (status IN ('Rascunho','Enviado','Recebido parcial','Recebido','Cancelado')),
  parcelas INTEGER NOT NULL DEFAULT 1 CHECK (parcelas BETWEEN 1 AND 60), primeiroVenc TEXT, intervaloDias INTEGER NOT NULL DEFAULT 30 CHECK (intervaloDias BETWEEN 1 AND 365),
  obs TEXT NOT NULL DEFAULT '', versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE TABLE pedidoItens (
  id TEXT PRIMARY KEY, pedidoId TEXT NOT NULL REFERENCES pedidos(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE, matId TEXT NOT NULL REFERENCES materiais(id) DEFERRABLE INITIALLY IMMEDIATE,
  qtd DOUBLE PRECISION NOT NULL CHECK (qtd > 0), precoUnitC BIGINT NOT NULL CHECK (precoUnitC >= 0), qtdRecebida DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (qtdRecebida >= 0)
);
CREATE INDEX ix_pitens_ped ON pedidoItens(pedidoId);

CREATE TABLE movimentacoes (
  id TEXT PRIMARY KEY, data TEXT NOT NULL, matId TEXT NOT NULL REFERENCES materiais(id) DEFERRABLE INITIALLY IMMEDIATE,
  tipo TEXT NOT NULL CHECK (tipo IN ('Entrada','Saída','Ajuste','Estorno')), sinal INTEGER NOT NULL CHECK (sinal IN (-1,1)),
  qtd DOUBLE PRECISION NOT NULL CHECK (qtd > 0), custoUnitC BIGINT NOT NULL DEFAULT 0 CHECK (custoUnitC >= 0),
  obraId TEXT REFERENCES obras(id) DEFERRABLE INITIALLY IMMEDIATE, passoId TEXT REFERENCES passos(id) DEFERRABLE INITIALLY IMMEDIATE, fornId TEXT REFERENCES fornecedores(id) DEFERRABLE INITIALLY IMMEDIATE, pedidoId TEXT REFERENCES pedidos(id) DEFERRABLE INITIALLY IMMEDIATE,
  doc TEXT NOT NULL DEFAULT '', motivo TEXT NOT NULL DEFAULT '', recId TEXT, estornoDe TEXT REFERENCES movimentacoes(id) DEFERRABLE INITIALLY IMMEDIATE, estornada INTEGER NOT NULL DEFAULT 0,
  estoqueAntes DOUBLE PRECISION NOT NULL DEFAULT 0, custoMedioAntesC BIGINT NOT NULL DEFAULT 0,
  criadoEm TEXT NOT NULL, criadoPor TEXT,
  CHECK (tipo <> 'Saída' OR obraId IS NOT NULL)
);
CREATE UNIQUE INDEX ux_mov_estorno ON movimentacoes(estornoDe) WHERE estornoDe IS NOT NULL;
CREATE INDEX ix_mov_mat ON movimentacoes(matId, data);
CREATE INDEX ix_mov_obra ON movimentacoes(obraId);
CREATE INDEX ix_mov_passo ON movimentacoes(passoId);
CREATE INDEX ix_mov_data ON movimentacoes(data);
CREATE INDEX ix_mov_rec ON movimentacoes(recId);

-- ---------- financeiro: título (conta) -> liquidação (baixa) -> estorno ----------
CREATE TABLE categoriasFin (
  id TEXT PRIMARY KEY, nome TEXT NOT NULL, tipo TEXT NOT NULL CHECK (tipo IN ('Receita','Despesa')),
  apropriaObra INTEGER NOT NULL DEFAULT 0, ativo INTEGER NOT NULL DEFAULT 1, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE UNIQUE INDEX ux_cat_nome ON categoriasFin(lower(nome));
CREATE TABLE bancos (
  id TEXT PRIMARY KEY, nome TEXT NOT NULL, tipo TEXT NOT NULL DEFAULT 'Banco' CHECK (tipo IN ('Caixa','Banco')),
  saldoInicialC BIGINT NOT NULL DEFAULT 0, ativo INTEGER NOT NULL DEFAULT 1, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE UNIQUE INDEX ux_bancos_nome ON bancos(lower(nome));
CREATE TABLE contratos (
  id TEXT PRIMARY KEY, obraId TEXT NOT NULL REFERENCES obras(id) DEFERRABLE INITIALLY IMMEDIATE, nome TEXT NOT NULL, empresa TEXT NOT NULL DEFAULT '', fornId TEXT REFERENCES fornecedores(id) DEFERRABLE INITIALLY IMMEDIATE,
  tipo TEXT NOT NULL DEFAULT 'Empreitada' CHECK (tipo IN ('Empreitada','Fornecimento','Serviço','Projeto','Locação','Outro')),
  status TEXT NOT NULL DEFAULT 'Vigente' CHECK (status IN ('Rascunho','Vigente','Encerrado','Rescindido')),
  valorC BIGINT NOT NULL DEFAULT 0 CHECK (valorC >= 0), inicio TEXT, fim TEXT, retencaoPct DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (retencaoPct >= 0 AND retencaoPct <= 100), obs TEXT NOT NULL DEFAULT '',
  ativo INTEGER NOT NULL DEFAULT 1, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE INDEX ix_contratos_obra ON contratos(obraId);
CREATE TABLE vendas (
  id TEXT PRIMARY KEY, unidadeId TEXT NOT NULL REFERENCES unidades(id) DEFERRABLE INITIALLY IMMEDIATE, clienteId TEXT NOT NULL REFERENCES clientes(id) DEFERRABLE INITIALLY IMMEDIATE, data TEXT NOT NULL,
  valorTotalC BIGINT NOT NULL CHECK (valorTotalC > 0), status TEXT NOT NULL DEFAULT 'Ativa' CHECK (status IN ('Ativa','Cancelada')),
  motivoCancelamento TEXT NOT NULL DEFAULT '', obs TEXT NOT NULL DEFAULT '', versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE UNIQUE INDEX ux_vendas_unid ON vendas(unidadeId) WHERE status = 'Ativa';
CREATE TABLE medicoes (
  id TEXT PRIMARY KEY, contratoId TEXT NOT NULL REFERENCES contratos(id) DEFERRABLE INITIALLY IMMEDIATE, numero INTEGER NOT NULL, data TEXT NOT NULL, descricao TEXT NOT NULL DEFAULT '',
  valorBrutoC BIGINT NOT NULL CHECK (valorBrutoC > 0), retencaoC BIGINT NOT NULL DEFAULT 0 CHECK (retencaoC >= 0), descontoC BIGINT NOT NULL DEFAULT 0 CHECK (descontoC >= 0),
  status TEXT NOT NULL DEFAULT 'Rascunho' CHECK (status IN ('Rascunho','Aprovada','Cancelada')), vencimento TEXT,
  versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT,
  UNIQUE (contratoId, numero)
);
CREATE TABLE folhas (
  id TEXT PRIMARY KEY, competencia TEXT NOT NULL UNIQUE, status TEXT NOT NULL DEFAULT 'Aberta' CHECK (status IN ('Aberta','Fechada')),
  fechadaEm TEXT, fechadaPor TEXT, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE TABLE folhaItens (
  id TEXT PRIMARY KEY, folhaId TEXT NOT NULL REFERENCES folhas(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE, funcId TEXT NOT NULL REFERENCES funcionarios(id) DEFERRABLE INITIALLY IMMEDIATE, obraId TEXT REFERENCES obras(id) DEFERRABLE INITIALLY IMMEDIATE,
  salarioBaseC BIGINT NOT NULL DEFAULT 0, encargosC BIGINT NOT NULL DEFAULT 0, adicionaisC BIGINT NOT NULL DEFAULT 0, descontosC BIGINT NOT NULL DEFAULT 0,
  UNIQUE (folhaId, funcId)
);
CREATE TABLE contas (
  id TEXT PRIMARY KEY, tipo TEXT NOT NULL CHECK (tipo IN ('Pagar','Receber')), descricao TEXT NOT NULL, valorC BIGINT NOT NULL CHECK (valorC > 0),
  vencimento TEXT NOT NULL, competencia TEXT NOT NULL, catId TEXT NOT NULL REFERENCES categoriasFin(id) DEFERRABLE INITIALLY IMMEDIATE,
  obraId TEXT REFERENCES obras(id) DEFERRABLE INITIALLY IMMEDIATE, empId TEXT REFERENCES empreendimentos(id) DEFERRABLE INITIALLY IMMEDIATE, passoId TEXT REFERENCES passos(id) DEFERRABLE INITIALLY IMMEDIATE, contratoId TEXT REFERENCES contratos(id) DEFERRABLE INITIALLY IMMEDIATE,
  medicaoId TEXT REFERENCES medicoes(id) DEFERRABLE INITIALLY IMMEDIATE, fornId TEXT REFERENCES fornecedores(id) DEFERRABLE INITIALLY IMMEDIATE, clienteId TEXT REFERENCES clientes(id) DEFERRABLE INITIALLY IMMEDIATE, vendaId TEXT REFERENCES vendas(id) DEFERRABLE INITIALLY IMMEDIATE,
  pedidoId TEXT REFERENCES pedidos(id) DEFERRABLE INITIALLY IMMEDIATE, folhaId TEXT REFERENCES folhas(id) DEFERRABLE INITIALLY IMMEDIATE, parcela INTEGER NOT NULL DEFAULT 1, parcelas INTEGER NOT NULL DEFAULT 1,
  doc TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'Aberta' CHECK (status IN ('Aberta','Cancelada')), motivoCancelamento TEXT NOT NULL DEFAULT '',
  obs TEXT NOT NULL DEFAULT '', origemChave TEXT UNIQUE,
  versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE INDEX ix_contas_tipo_venc ON contas(tipo, vencimento);
CREATE INDEX ix_contas_obra ON contas(obraId);
CREATE INDEX ix_contas_contrato ON contas(contratoId);
CREATE INDEX ix_contas_venda ON contas(vendaId);
CREATE INDEX ix_contas_comp ON contas(competencia);
CREATE TABLE liquidacoes (
  id TEXT PRIMARY KEY, contaId TEXT NOT NULL REFERENCES contas(id) DEFERRABLE INITIALLY IMMEDIATE, data TEXT NOT NULL,
  valorC BIGINT NOT NULL CHECK (valorC > 0),            -- quanto do título foi baixado
  descontoC BIGINT NOT NULL DEFAULT 0 CHECK (descontoC >= 0), jurosC BIGINT NOT NULL DEFAULT 0 CHECK (jurosC >= 0), multaC BIGINT NOT NULL DEFAULT 0 CHECK (multaC >= 0),
  caixaC BIGINT NOT NULL,                               -- dinheiro que realmente entrou/saiu = valor - desconto + juros + multa
  forma TEXT NOT NULL DEFAULT '', bancoId TEXT REFERENCES bancos(id) DEFERRABLE INITIALLY IMMEDIATE, doc TEXT NOT NULL DEFAULT '', obs TEXT NOT NULL DEFAULT '',
  estornadaEm TEXT, estornadaPor TEXT, motivoEstorno TEXT NOT NULL DEFAULT '', criadoEm TEXT NOT NULL, criadoPor TEXT,
  CHECK (descontoC <= valorC)
);
CREATE INDEX ix_liq_conta ON liquidacoes(contaId);
CREATE INDEX ix_liq_data ON liquidacoes(data);
CREATE INDEX ix_liq_banco ON liquidacoes(bancoId);

-- ---------- rotina de obra ----------
CREATE TABLE tarefas (
  id TEXT PRIMARY KEY, titulo TEXT NOT NULL, obraId TEXT REFERENCES obras(id) DEFERRABLE INITIALLY IMMEDIATE, passoId TEXT REFERENCES passos(id) DEFERRABLE INITIALLY IMMEDIATE, respId TEXT REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  prio TEXT NOT NULL DEFAULT 'Média' CHECK (prio IN ('Alta','Média','Baixa')), status TEXT NOT NULL DEFAULT 'Aberta' CHECK (status IN ('Aberta','Em andamento','Resolvida')),
  prazo TEXT, obs TEXT NOT NULL DEFAULT '', ativo INTEGER NOT NULL DEFAULT 1, versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT
);
CREATE INDEX ix_tarefas_obra ON tarefas(obraId);
CREATE TABLE diario (
  id TEXT PRIMARY KEY, obraId TEXT NOT NULL REFERENCES obras(id) DEFERRABLE INITIALLY IMMEDIATE, data TEXT NOT NULL,
  clima TEXT NOT NULL DEFAULT 'Bom' CHECK (clima IN ('Bom','Nublado','Chuva leve','Chuva forte')), equipe INTEGER NOT NULL DEFAULT 0 CHECK (equipe >= 0),
  servicos TEXT NOT NULL DEFAULT '', ocorrencias TEXT NOT NULL DEFAULT '', ativo INTEGER NOT NULL DEFAULT 1,
  versao INTEGER NOT NULL DEFAULT 1, criadoEm TEXT NOT NULL, atualizadoEm TEXT NOT NULL, criadoPor TEXT, atualizadoPor TEXT,
  UNIQUE (obraId, data)
);
CREATE TABLE documentos (
  id TEXT PRIMARY KEY, entidade TEXT NOT NULL, entidadeId TEXT NOT NULL, nome TEXT NOT NULL, tipo TEXT NOT NULL DEFAULT 'Outro', validade TEXT,
  mime TEXT NOT NULL, tamanho INTEGER NOT NULL, arquivo TEXT NOT NULL, sha256 TEXT NOT NULL, criadoEm TEXT NOT NULL, criadoPor TEXT
);
CREATE INDEX ix_docs_ent ON documentos(entidade, entidadeId);
CREATE TABLE alocacoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, funcId TEXT NOT NULL REFERENCES funcionarios(id) DEFERRABLE INITIALLY IMMEDIATE, obraId TEXT REFERENCES obras(id) DEFERRABLE INITIALLY IMMEDIATE, de TEXT NOT NULL, ate TEXT
);
CREATE INDEX ix_aloc_func ON alocacoes(funcId);

